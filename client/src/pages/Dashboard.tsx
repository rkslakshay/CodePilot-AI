import { useEffect, useState } from 'react';
import { Link, useNavigate } from 'react-router';
import { Activity, BookOpen, Bug, Code2, Database, FileCode2, FolderKanban, GitBranch, MessageSquareCode, PlayCircle, Shuffle, Sparkles, Trash2, TrendingUp, Trophy, Bot, Cpu, ArrowRight, History, CheckCircle2, XCircle, Shapes } from 'lucide-react';
import { api } from '@/lib/api';
import { Badge, Button, Card, CardHeader, EmptyState, Skeleton, Stat, Alert } from '@/components/ui/primitives';
import { confirmAction, toast } from '@/components/ui/overlay';
import { LangDot, LangTag } from '@/components/common';
import { langColor, langLabel, timeAgo, cn } from '@/lib/utils';
import { useAi, useSettings } from '@/store';
import type { HistoryItem, Project, CodeFile } from '@/lib/types';

interface Dash {
  totals: Record<string, number | null>;
  languages: { language: string; count: number }[];
  activity: { day: string; count: number }[];
  recentProjects: Project[];
  recentFiles: CodeFile[];
  recentGenerations: HistoryItem[];
  recentConversions: HistoryItem[];
  recentActivity: (HistoryItem & { kind: string })[];
  savedAlgorithms: { id: number; title: string; isDemo: boolean; createdAt: string }[];
  hasDemoData: boolean;
  continue?: {
    file: { id: number; name: string; language: string; projectName: string; updatedAt: string } | null;
    work: { id: number; kind: string; title: string; language: string | null; createdAt: string; route: string } | null;
    topics: { topicId: string; title: string; quizCorrect: number; quizTotal: number }[];
  };
  engines?: { engine: 'ollama' | 'offline' | 'template'; count: number }[];
  toolchain?: {
    runtimes: { language: string; label: string; available: boolean; version: string | null }[];
    executionEnabled: boolean;
    isolation: 'job+lowil' | 'job' | 'process';
    sandbox: boolean;
  };
}

const ENGINE_META: Record<string, { label: string; hint: string; color: string }> = {
  ollama: { label: 'Local AI (Ollama)', hint: 'Generated by a model running on this computer', color: 'var(--primary)' },
  offline: { label: 'Offline engine', hint: 'Rule-based parser, analyser and translator', color: 'var(--secondary)' },
  template: { label: 'Built-in templates', hint: 'Hand-written reference programs', color: 'var(--warning)' },
};
const KIND_VERB: Record<string, string> = { generation: 'Generated', conversion: 'Converted', explanation: 'Explained', algorithm: 'Visualised', execution: 'Ran', debug: 'Debugged' };

const TOOLS = [
  { to: '/generator', label: 'Code Generator', icon: Code2, desc: 'Problem → working program', tone: 'from-primary/25' },
  { to: '/converter', label: 'Code Converter', icon: Shuffle, desc: 'Translate across 5 languages', tone: 'from-info/25' },
  { to: '/studio', label: 'Algorithm Studio', icon: GitBranch, desc: 'Flowcharts & visual dry runs', tone: 'from-secondary/25' },
  { to: '/explainer', label: 'Code Explainer', icon: MessageSquareCode, desc: 'Line-by-line understanding', tone: 'from-warning/25' },
  { to: '/compiler', label: 'Compiler & Debugger', icon: Bug, desc: 'Run, test and fix locally', tone: 'from-danger/25' },
  { to: '/uml', label: 'UML Studio', icon: Shapes, desc: '8 UML diagram types, offline', tone: 'from-info/25' },
  { to: '/learning', label: 'Learning Hub', icon: BookOpen, desc: 'Viva, MCQs, practice', tone: 'from-primary/25' },
];

const KIND_ICON: Record<string, typeof Code2> = { generation: Code2, conversion: Shuffle, explanation: MessageSquareCode, algorithm: GitBranch, execution: PlayCircle, debug: Bug, learning: BookOpen };

export default function Dashboard() {
  const [d, setD] = useState<Dash | null>(null);
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);
  const nav = useNavigate();
  const load = () =>
    api
      .get<Dash>('/dashboard')
      .then((x) => {
        setD(x);
        setError('');
      })
      .catch((e) => setError(e.message));
  useEffect(() => {
    void load();
  }, []);

  const loadDemo = async () => {
    setBusy(true);
    try {
      const r = await api.post<Record<string, number>>('/demo/load');
      toast.success('Demonstration data loaded', `${r.projects} projects, ${r.files} files and ${r.history} history records (all marked as demo).`);
      await load();
    } catch (e) {
      toast.error('Could not load demo data', (e as Error).message);
    } finally {
      setBusy(false);
    }
  };
  const clearDemo = async () => {
    if (!(await confirmAction({ title: 'Remove demonstration data?', description: 'Only records marked as demo are deleted. Your own projects and history are kept.', confirmLabel: 'Remove demo data' }))) return;
    await api.post('/demo/clear');
    toast.success('Demo data removed');
    await load();
  };

  if (error) return <Alert tone="danger" title="Dashboard unavailable">{error}</Alert>;
  if (!d) return <DashSkeleton />;
  const t = d.totals;
  const isEmpty = (t.activities ?? 0) === 0 && (t.projects ?? 0) === 0;
  const hour = new Date().getHours();
  const greet = hour < 12 ? 'Good morning' : hour < 18 ? 'Good afternoon' : 'Good evening';

  return (
    <div className="space-y-5">
      <Card className="relative overflow-hidden p-6">
        <div className="pointer-events-none absolute -top-24 -right-16 h-64 w-64 rounded-full bg-primary/20 blur-3xl" />
        <div className="pointer-events-none absolute -bottom-24 left-1/3 h-56 w-56 rounded-full bg-secondary/10 blur-3xl" />
        <div className="relative flex flex-wrap items-center justify-between gap-4">
          <div>
            <p className="text-[13px] font-medium text-primary">{greet} 👋</p>
            <h1 className="mt-1 text-2xl font-semibold tracking-tight">Welcome to CodePilot AI</h1>
            <p className="mt-1 max-w-xl text-[13.5px] text-muted">Your AI-powered programming companion — generate, convert, understand, visualise, run and debug code in one workspace. Everything runs on this computer.</p>
          </div>
          <div className="flex flex-wrap gap-2">
            {d.hasDemoData ? (
              <Button variant="outline" icon={Trash2} onClick={clearDemo}>
                Remove demo data
              </Button>
            ) : (
              <Button variant="secondary" icon={Database} loading={busy} onClick={loadDemo}>
                Load demo data
              </Button>
            )}
            <Button variant="primary" icon={Sparkles} onClick={() => nav('/generator')}>
              Generate code
            </Button>
          </div>
        </div>
      </Card>

      <div className="grid grid-cols-2 gap-3 md:grid-cols-4 xl:grid-cols-7">
        {TOOLS.map((tl) => (
          <Link key={tl.to} to={tl.to} className="group">
            <Card className={cn('h-full bg-gradient-to-br to-transparent p-4 transition-all group-hover:-translate-y-0.5 group-hover:border-border-strong', tl.tone)}>
              <tl.icon size={20} className="text-fg" />
              <p className="mt-3 text-[13.5px] font-semibold">{tl.label}</p>
              <p className="mt-0.5 text-xs text-muted">{tl.desc}</p>
            </Card>
          </Link>
        ))}
      </div>

      {d.continue && (d.continue.file || d.continue.work || d.continue.topics.length > 0) && <ContinueCard c={d.continue} />}

      {isEmpty && (
        <Alert tone="primary" icon={Sparkles} title="Your workspace is empty" action={<Button size="sm" variant="primary" loading={busy} onClick={loadDemo}>Load demo data</Button>}>
          Statistics below are computed from your local database. Start using a tool, or load clearly-labelled demonstration content to explore the app.
        </Alert>
      )}

      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Stat label="Code generated" value={t.generations ?? 0} icon={Code2} hint={`${t.conversions ?? 0} conversions · ${t.explanations ?? 0} explanations`} />
        <Stat label="Programs run" value={t.executions ?? 0} icon={PlayCircle} tone="secondary" hint={t.executionSuccessRate !== null ? `${t.executionSuccessRate}% successful` : 'No runs yet'} />
        <Stat label="Projects · files" value={`${t.projects ?? 0} · ${t.files ?? 0}`} icon={FolderKanban} tone="info" hint={`${t.savedAlgorithms ?? 0} saved algorithms`} />
        <Stat label="Topics completed" value={`${t.topicsCompleted}/${t.topicsTotal}`} icon={Trophy} tone="warning" hint={[t.topicsInProgress ? `${t.topicsInProgress} in progress` : '', t.quizAccuracy !== null ? `quiz accuracy ${t.quizAccuracy}%` : ''].filter(Boolean).join(' · ') || 'Start a topic in the Learning Hub'} />
      </div>

      <div className="grid gap-4 xl:grid-cols-3">
        <Card className="xl:col-span-2">
          <CardHeader title="Programming activity" subtitle="Operations per day, last 14 days" icon={TrendingUp} actions={<Badge tone="secondary">{t.streakDays ?? 0}-day streak</Badge>} />
          <div className="p-4">
            <ActivityChart data={d.activity} />
          </div>
        </Card>
        <Card>
          <CardHeader title="Language usage" subtitle="Across history and saved files" icon={Activity} />
          <div className="p-4">
            {d.languages.length ? <LanguageBars data={d.languages} /> : <EmptyState icon={Activity} title="No language data yet" description="Language usage appears after you generate, convert or save code." />}
          </div>
        </Card>
      </div>

      <div className="grid gap-4 lg:grid-cols-2 xl:grid-cols-3">
        <Card>
          <CardHeader title="Recent projects" icon={FolderKanban} actions={<Link to="/workspace" className="text-xs text-primary hover:underline">View all</Link>} />
          {d.recentProjects.length ? (
            <ul className="divide-y divide-border">
              {d.recentProjects.map((p) => (
                <li key={p.id}>
                  <Link to={`/workspace?project=${p.id}`} className="flex items-center gap-3 px-4 py-2.5 hover:bg-elevated/50">
                    <FolderKanban size={16} className="text-muted" />
                    <div className="min-w-0 flex-1">
                      <p className="truncate text-[13px] font-medium">{p.name}</p>
                      <p className="text-[11.5px] text-subtle">
                        {p.fileCount} {p.fileCount === 1 ? 'file' : 'files'} · {timeAgo(p.updatedAt)}
                      </p>
                    </div>
                    {p.isDemo && <Badge>demo</Badge>}
                  </Link>
                </li>
              ))}
            </ul>
          ) : (
            <EmptyState icon={FolderKanban} title="No projects yet" action={<Button size="sm" onClick={() => nav('/workspace?new=1')}>Create project</Button>} />
          )}
        </Card>
        <HistoryCard title="Recently generated code" icon={Code2} items={d.recentGenerations} empty="Generated programs will appear here." />
        <HistoryCard title="Recent conversions" icon={Shuffle} items={d.recentConversions} empty="Converted code will appear here." />
        <Card>
          <CardHeader title="Recently used files" icon={FileCode2} />
          {d.recentFiles.length ? (
            <ul className="divide-y divide-border">
              {d.recentFiles.map((f) => (
                <li key={f.id}>
                  <Link to={`/workspace?file=${f.id}`} className="flex items-center gap-3 px-4 py-2.5 hover:bg-elevated/50">
                    <LangDot lang={f.language} />
                    <span className="min-w-0 flex-1 truncate font-mono text-[12.5px]">{f.name}</span>
                    <span className="truncate text-[11.5px] text-subtle">{f.projectName}</span>
                  </Link>
                </li>
              ))}
            </ul>
          ) : (
            <EmptyState icon={FileCode2} title="No files yet" />
          )}
        </Card>
        <Card>
          <CardHeader title="Saved algorithms" icon={GitBranch} actions={<Link to="/studio?tab=saved" className="text-xs text-primary hover:underline">Open studio</Link>} />
          {d.savedAlgorithms.length ? (
            <ul className="divide-y divide-border">
              {d.savedAlgorithms.map((a) => (
                <li key={a.id}>
                  <Link to={`/studio?saved=${a.id}`} className="flex items-center gap-3 px-4 py-2.5 hover:bg-elevated/50">
                    <GitBranch size={15} className="text-secondary" />
                    <span className="min-w-0 flex-1 truncate text-[13px]">{a.title}</span>
                    {a.isDemo && <Badge>demo</Badge>}
                  </Link>
                </li>
              ))}
            </ul>
          ) : (
            <EmptyState icon={GitBranch} title="No saved algorithms" description="Save an algorithm from the Algorithm Studio." />
          )}
        </Card>
        <AiCard />
        {d.engines && <EnginesCard engines={d.engines} />}
        {d.toolchain && <ToolchainCard tc={d.toolchain} />}
      </div>

      <Card>
        <CardHeader title="Recent activity" icon={Activity} actions={<Link to="/history" className="text-xs text-primary hover:underline">Full history</Link>} />
        {d.recentActivity.length ? (
          <ul className="divide-y divide-border">
            {d.recentActivity.map((h) => {
              const I = KIND_ICON[h.kind] ?? Activity;
              return (
                <li key={h.id}>
                  <Link to={`/history?id=${h.id}`} className="flex items-center gap-3 px-4 py-2.5 hover:bg-elevated/50">
                    <span className="grid h-7 w-7 place-items-center rounded-lg bg-elevated text-muted">
                      <I size={14} />
                    </span>
                    <span className="min-w-0 flex-1 truncate text-[13px]">{h.title}</span>
                    {h.language && <LangTag lang={h.language} />}
                    <span className="hidden w-20 text-right text-[11.5px] text-subtle sm:block">{timeAgo(h.createdAt)}</span>
                  </Link>
                </li>
              );
            })}
          </ul>
        ) : (
          <EmptyState icon={Activity} title="No activity yet" description="Every generation, conversion, explanation and run is recorded locally." />
        )}
      </Card>
    </div>
  );
}

function ContinueCard({ c }: { c: NonNullable<Dash['continue']> }) {
  return (
    <Card>
      <CardHeader title="Continue where you left off" icon={History} />
      <div className="grid gap-2 p-2 sm:grid-cols-2 lg:grid-cols-3">
        {c.file && (
          <Link to={`/workspace?file=${c.file.id}`} className="group flex items-center gap-3 rounded-lg border border-transparent p-3 transition-colors hover:border-border hover:bg-elevated/60">
            <span className="grid h-9 w-9 shrink-0 place-items-center rounded-lg bg-info/15 text-info">
              <FileCode2 size={17} />
            </span>
            <span className="min-w-0 flex-1">
              <span className="block text-[11.5px] text-subtle">Last edited file · {timeAgo(c.file.updatedAt)}</span>
              <span className="block truncate font-mono text-[13px] font-medium">{c.file.name}</span>
              <span className="block truncate text-[11.5px] text-muted">{c.file.projectName}</span>
            </span>
            <ArrowRight size={15} className="text-subtle transition-transform group-hover:translate-x-0.5" />
          </Link>
        )}
        {c.work && (
          <Link to={`/history?id=${c.work.id}`} className="group flex items-center gap-3 rounded-lg border border-transparent p-3 transition-colors hover:border-border hover:bg-elevated/60">
            <span className="grid h-9 w-9 shrink-0 place-items-center rounded-lg bg-primary/15 text-primary">
              {(() => {
                const I = KIND_ICON[c.work.kind] ?? Activity;
                return <I size={17} />;
              })()}
            </span>
            <span className="min-w-0 flex-1">
              <span className="block text-[11.5px] text-subtle">
                {KIND_VERB[c.work.kind] ?? 'Worked on'} · {timeAgo(c.work.createdAt)}
              </span>
              <span className="block truncate text-[13px] font-medium">{c.work.title}</span>
              {c.work.language && <span className="block text-[11.5px] text-muted">{langLabel(c.work.language)}</span>}
            </span>
            <ArrowRight size={15} className="text-subtle transition-transform group-hover:translate-x-0.5" />
          </Link>
        )}
        {c.topics.map((t) => (
          <Link key={t.topicId} to={`/learning?topic=${t.topicId}`} className="group flex items-center gap-3 rounded-lg border border-transparent p-3 transition-colors hover:border-border hover:bg-elevated/60">
            <span className="grid h-9 w-9 shrink-0 place-items-center rounded-lg bg-warning/15 text-warning">
              <BookOpen size={17} />
            </span>
            <span className="min-w-0 flex-1">
              <span className="block text-[11.5px] text-subtle">Learning · in progress</span>
              <span className="block truncate text-[13px] font-medium">{t.title}</span>
              <span className="block text-[11.5px] text-muted">{t.quizTotal ? `Quiz ${t.quizCorrect}/${t.quizTotal} correct` : 'No quiz attempts yet'}</span>
            </span>
            <ArrowRight size={15} className="text-subtle transition-transform group-hover:translate-x-0.5" />
          </Link>
        ))}
      </div>
    </Card>
  );
}

function EnginesCard({ engines }: { engines: NonNullable<Dash['engines']> }) {
  const total = engines.reduce((a, e) => a + e.count, 0);
  const order = ['ollama', 'offline', 'template'] as const;
  return (
    <Card>
      <CardHeader title="How results were produced" subtitle="Every history record stores its engine" icon={Sparkles} />
      <div className="space-y-3 p-4">
        {total ? (
          <>
            <div className="flex h-2.5 overflow-hidden rounded-full bg-elevated" role="img" aria-label="Share of results by engine">
              {order.map((k) => {
                const c = engines.find((e) => e.engine === k)?.count ?? 0;
                return c ? <div key={k} style={{ width: `${(c / total) * 100}%`, background: ENGINE_META[k].color }} /> : null;
              })}
            </div>
            {order.map((k) => {
              const c = engines.find((e) => e.engine === k)?.count ?? 0;
              return (
                <div key={k} className="flex items-center gap-2.5 text-[13px]">
                  <span className="h-2.5 w-2.5 rounded-full" style={{ background: ENGINE_META[k].color }} />
                  <span className="min-w-0 flex-1">
                    <span className="block">{ENGINE_META[k].label}</span>
                    <span className="block text-[11.5px] text-subtle">{ENGINE_META[k].hint}</span>
                  </span>
                  <span className="font-mono text-xs text-muted">{c}</span>
                  <span className="w-10 text-right font-mono text-xs text-subtle">{Math.round((c / total) * 100)}%</span>
                </div>
              );
            })}
          </>
        ) : (
          <EmptyState icon={Sparkles} title="No results yet" description="Each result is labelled Local AI, offline engine or built-in template." />
        )}
      </div>
    </Card>
  );
}

function ToolchainCard({ tc }: { tc: NonNullable<Dash['toolchain']> }) {
  const ready = tc.runtimes.filter((r) => r.available).length;
  return (
    <Card>
      <CardHeader
        title="Compilers & runtimes"
        subtitle={`${ready} of ${tc.runtimes.length} languages can run`}
        icon={Cpu}
        actions={<Badge tone={!tc.executionEnabled ? 'neutral' : tc.sandbox ? 'success' : 'warning'}>{!tc.executionEnabled ? 'Execution off' : tc.sandbox ? 'Sandboxed' : 'Guarded process'}</Badge>}
      />
      <ul className="divide-y divide-border">
        {tc.runtimes.map((r) => (
          <li key={r.language} className="flex items-center gap-2.5 px-4 py-2">
            {r.available ? <CheckCircle2 size={15} className="shrink-0 text-success" /> : <XCircle size={15} className="shrink-0 text-danger" />}
            <span className="w-20 text-[13px] font-medium">{r.label}</span>
            <span className="min-w-0 flex-1 truncate text-right text-[11.5px] text-subtle" title={r.version ?? ''}>
              {r.available ? r.version : 'not installed'}
            </span>
          </li>
        ))}
      </ul>
      <div className="border-t border-border px-4 py-2.5">
        <Link to="/compiler" className="inline-flex items-center gap-1 text-[12.5px] text-primary hover:underline">
          Open compiler <ArrowRight size={13} />
        </Link>
      </div>
    </Card>
  );
}

function HistoryCard({ title, icon, items, empty }: { title: string; icon: typeof Code2; items: HistoryItem[]; empty: string }) {
  return (
    <Card>
      <CardHeader title={title} icon={icon} />
      {items.length ? (
        <ul className="divide-y divide-border">
          {items.map((h) => (
            <li key={h.id}>
              <Link to={`/history?id=${h.id}`} className="flex items-center gap-3 px-4 py-2.5 hover:bg-elevated/50">
                <div className="min-w-0 flex-1">
                  <p className="truncate text-[13px]">{h.title}</p>
                  <p className="text-[11.5px] text-subtle">
                    {langLabel(h.language)}
                    {h.targetLanguage ? ` → ${langLabel(h.targetLanguage)}` : ''} · {timeAgo(h.createdAt)}
                  </p>
                </div>
                {h.isDemo && <Badge>demo</Badge>}
              </Link>
            </li>
          ))}
        </ul>
      ) : (
        <EmptyState icon={icon} title="Nothing yet" description={empty} />
      )}
    </Card>
  );
}

function AiCard() {
  const status = useAi((s) => s.status);
  const mode = useSettings((s) => s.settings.aiProvider);
  const connected = mode === 'ollama' && status?.reachable && status.modelInstalled;
  return (
    <Card>
      <CardHeader title="AI provider" icon={connected ? Bot : Cpu} actions={<Badge tone={connected ? 'success' : mode === 'ollama' ? 'warning' : 'neutral'}>{connected ? 'Connected' : mode === 'ollama' ? 'Not ready' : 'Offline mode'}</Badge>} />
      <div className="space-y-3 p-4 text-[13px] text-muted">
        {connected ? (
          <p>
            Local AI is active using <span className="font-mono text-fg">{status!.selectedModel}</span> via Ollama {status!.version}. Your code never leaves this computer.
          </p>
        ) : mode === 'ollama' ? (
          <p>{status?.reachable ? 'Ollama is running but the selected model is not installed.' : `Ollama is not reachable at ${status?.url ?? 'localhost:11434'}.`} Results fall back to the offline engine, and every result is labelled.</p>
        ) : (
          <p>The offline engine provides templates, structured conversion, static analysis and visualisations without any AI model. Install the free Ollama app to enable local AI (optional).</p>
        )}
        <Link to="/settings#ai" className="inline-flex items-center gap-1 text-primary hover:underline">
          Configure AI <ArrowRight size={13} />
        </Link>
      </div>
    </Card>
  );
}

function ActivityChart({ data }: { data: { day: string; count: number }[] }) {
  const max = Math.max(1, ...data.map((d) => d.count));
  return (
    <div>
      <div className="flex h-40 items-end gap-1.5" role="img" aria-label="Daily activity bar chart">
        {data.map((d) => (
          <div key={d.day} className="group relative flex h-full flex-1 flex-col justify-end">
            <div className="w-full rounded-t-md bg-gradient-to-t from-primary/70 to-primary transition-all group-hover:brightness-125" style={{ height: `${Math.max(d.count ? 6 : 2, (d.count / max) * 100)}%`, opacity: d.count ? 1 : 0.25 }} />
            <span className="pointer-events-none absolute -top-6 left-1/2 -translate-x-1/2 rounded bg-elevated px-1.5 py-0.5 text-[11px] whitespace-nowrap opacity-0 group-hover:opacity-100">{d.count}</span>
          </div>
        ))}
      </div>
      <div className="mt-2 flex gap-1.5">
        {data.map((d, i) => (
          <span key={d.day} className="flex-1 text-center text-[10px] text-subtle">
            {i % 2 === 0 ? new Date(d.day + 'T00:00:00Z').toLocaleDateString(undefined, { day: 'numeric', month: 'short', timeZone: 'UTC' }) : ''}
          </span>
        ))}
      </div>
    </div>
  );
}

function LanguageBars({ data }: { data: { language: string; count: number }[] }) {
  const total = data.reduce((a, b) => a + b.count, 0);
  return (
    <div className="space-y-3">
      <div className="flex h-2.5 overflow-hidden rounded-full bg-elevated">
        {data.map((d) => (
          <div key={d.language} style={{ width: `${(d.count / total) * 100}%`, background: langColor(d.language) }} title={langLabel(d.language)} />
        ))}
      </div>
      {data.map((d) => (
        <div key={d.language} className="flex items-center gap-2.5 text-[13px]">
          <LangDot lang={d.language} />
          <span className="flex-1">{langLabel(d.language)}</span>
          <span className="font-mono text-xs text-muted">{d.count}</span>
          <span className="w-10 text-right font-mono text-xs text-subtle">{Math.round((d.count / total) * 100)}%</span>
        </div>
      ))}
    </div>
  );
}

