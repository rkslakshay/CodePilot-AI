export function EngineBadge({ engine, className }: { engine: Engine; className?: string }) {
  const meta: Record<Engine['kind'], { icon: LucideIcon; tone: 'primary' | 'secondary' | 'neutral'; tip: string }> = {
    ollama: { icon: Bot, tone: 'primary', tip: 'Generated by a local language model running in Ollama on this computer.' },
    template: { icon: FileCode2, tone: 'secondary', tip: 'Built-in content verified by automated tests. Not AI-generated.' },
    offline: { icon: Cpu, tone: 'neutral', tip: 'Produced by deterministic rule-based analysis. Not AI-generated.' },
  };
  const m = meta[engine.kind];
  return (
    <Tooltip label={m.tip} side="bottom" className={className}>
      <Badge tone={m.tone} icon={m.icon}>
        {engine.label}
      </Badge>
    </Tooltip>
  );
}

export function EngineNotice({ engine }: { engine?: Engine | null }) {
  if (!engine?.notice) return null;
  return (
    <div className="flex items-start gap-2 rounded-lg border border-warning/25 bg-warning-soft px-3 py-2 text-xs text-warning">
      <AlertTriangle size={14} className="mt-0.5 shrink-0" />
      <span className="text-fg/85">{engine.notice}</span>
    </div>
  );
}

export function LanguageSelect({ value, onChange, className, exclude, ariaLabel = 'Language' }: { value: Lang; onChange: (l: Lang) => void; className?: string; exclude?: Lang; ariaLabel?: string }) {
  return (
    <Select aria-label={ariaLabel} value={value} onChange={(e) => onChange(e.target.value as Lang)} className={cn('w-[140px]', className)}>
      {LANGS.filter((l) => l.id !== exclude).map((l) => (
        <option key={l.id} value={l.id}>
          {l.label}
        </option>
      ))}
    </Select>
  );
}

export function LangDot({ lang, className }: { lang?: string | null; className?: string }) {
  return <span className={cn('inline-block h-2 w-2 shrink-0 rounded-full', className)} style={{ background: langColor(lang) }} />;
}

