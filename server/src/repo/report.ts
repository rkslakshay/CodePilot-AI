/**
 * Repository analysis report: Markdown (always) and PDF (rendered from HTML by the locally
 * installed Microsoft Edge / Chrome in headless mode — no network, no downloads).
 */
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { execFile } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { config } from '../config.js';
import { getSettings } from '../services/settings.js';
import { overview, dependencies, complexity, debt, listFindings } from './service.js';
import { lastScopeReview } from './review.js';
import { RULES, SEVERITY_ORDER } from './rules.js';

const esc = (s: unknown) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const SEV_LABEL: Record<string, string> = { critical: 'Critical', high: 'High', medium: 'Medium', low: 'Low', info: 'Info' };

export function buildReport(repoId: number): { markdown: string; title: string; complete: boolean } {
  const ov = overview(repoId);
  const repo = ov.repo;
  if (!ov.stats) throw Object.assign(new Error('The repository has not been analysed yet.'), { status: 409 });
  const s = ov.stats;
  const a = repo.analysis as any;
  const p = repo.profile as any;
  const deps = dependencies(repoId);
  const cx = complexity(repoId);
  const td = debt(repoId);
  const sec = listFindings(repoId, { category: 'security', limit: 500 }).items.filter((f: any) => f.status !== 'dismissed');
  const quality = listFindings(repoId, { category: 'bug,maintainability,performance,complexity,style', limit: 500 }).items.filter((f: any) => f.status !== 'dismissed');
  const dismissed = listFindings(repoId, { status: 'dismissed', limit: 1 }).total;
  const fixed = listFindings(repoId, { status: 'fixed', limit: 1 }).total;
  const ai = lastScopeReview(repoId);
  const settings = getSettings();
  const complete = !!a.complete;
  const date = new Date().toISOString().replace('T', ' ').slice(0, 16) + ' UTC';
  const L: string[] = [];
  L.push(`# Code Quality Report — ${repo.name}`, '');
  L.push(complete ? '> Automated static analysis of the whole repository. It is **not** a manual security audit.' : '> **Partial analysis** — not all files could be analysed (see Limitations). This is not a complete audit.', '');
  L.push('| Field | Value |', '|---|---|');
  L.push(`| Report generated | ${date} |`);
  L.push(`| Last analysis | ${repo.analyzedAt} UTC |`);
  L.push(`| Repository | ${esc(repo.name)} (id ${repo.id}, ${repo.source === 'zip' ? 'imported ZIP archive' : 'local folder'}) |`);
  L.push(`| Generated by | ${config.appName} ${config.version} |`);
  L.push(`| Analysis engines | ${esc(a.tools?.treeSitter)}; ${a.tools?.codepilotRules} CodePilot rules; external tools: ${(a.tools?.external ?? []).filter((t: any) => t.ran).map((t: any) => `${t.name} ${t.version ?? ''}`).join(', ') || 'none run'} |`);
  L.push(`| AI model | ${ai?.aiAvailable ? `Local AI via Ollama (${esc(settings.ollamaModel)}) — ${ai.reviewed} file(s) reviewed` : 'not used (static analysis only)'} |`, '');

  L.push('## 1. Overview', '');
  L.push(`**Quality score: ${s.quality.score}/100 (grade ${s.quality.grade})** — ${s.quality.weighted} weighted findings over ${s.quality.kloc} KLOC.`, '');
  L.push(`Formula: \`${s.quality.formula}\`.`, '');
  L.push('| Metric | Value |', '|---|---|');
  for (const [k, v] of [
    ['Files analysed', s.totalFiles],
    ['Source files', s.sourceFiles],
    ['Test files', s.testFiles],
    ['Documentation files', s.docFiles],
    ['Directories', s.directories],
    ['Lines of code (source + tests)', s.linesOfCode],
    ['Functions', s.functions],
    ['Classes', s.classes],
    ['Direct dependencies', s.dependencies],
    ['Repository size', `${(s.totalBytes / 1024).toFixed(1)} KB`],
  ] as const)
    L.push(`| ${k} | ${v} |`);
  L.push('');
  L.push(`Project type: ${(p.projectTypes ?? []).join(', ') || 'unknown'}. Frameworks: ${(p.frameworks ?? []).map((f: any) => f.name).join(', ') || 'none detected'}. Package managers: ${(a.managers ?? []).join(', ') || 'none'}.`, '');

  L.push('## 2. Languages', '', '| Language | Files | Lines |', '|---|---:|---:|');
  for (const l of s.languages.slice(0, 15)) L.push(`| ${l.language} | ${l.files} | ${l.lines} |`);
  L.push('');

  L.push('## 3. Findings breakdown', '', '| Severity | Count |', '|---|---:|');
  for (const k of SEVERITY_ORDER) L.push(`| ${SEV_LABEL[k]} | ${s.findingsBySeverity[k]} |`);
  L.push('', '| Category | Count |', '|---|---:|');
  for (const [k, v] of Object.entries(s.findingsByCategory)) L.push(`| ${k} | ${v} |`);
  L.push('', `${dismissed} finding(s) were dismissed as false positives and ${fixed} marked fixed by the user; they are excluded above.`, '');

  const table = (rows: any[], n: number) => {
    L.push('| Severity | Confidence | Location | Finding | Source |', '|---|---|---|---|---|');
    for (const f of rows.slice(0, n)) L.push(`| ${SEV_LABEL[f.severity]} | ${f.confidence} | \`${esc(f.path)}${f.line ? `:${f.line}` : ''}\` | **${esc(f.title)}** — ${esc(f.description).slice(0, 220)} | ${f.source === 'ai' ? 'Local AI' : f.source === 'combined' ? 'Static + AI' : f.source === 'tool' ? esc(f.tool) : 'Static'}${f.userVerified ? ' (user-verified)' : ''} |`);
    if (rows.length > n) L.push('', `…and ${rows.length - n} more (see CodePilot AI).`);
    L.push('');
  };
  L.push('## 4. Security findings', '', '> Static analysis cannot prove the absence of vulnerabilities. No findings does not mean the code is secure.', '');
  if (sec.length) table(sec, 40);
  else L.push('No security patterns were detected by the rules that ran.', '');
  L.push('## 5. Code quality findings', '');
  if (quality.length) table(quality, 40);
  else L.push('No quality findings.', '');

  L.push('## 6. Complexity', '', `${cx.functions} functions; average cyclomatic complexity ${cx.averageComplexity}, median ${cx.medianComplexity}. ${cx.method}`, '', '| Complexity | Functions |', '|---|---:|');
  for (const b of cx.distribution) L.push(`| ${b.label} | ${b.count} |`);
  L.push('', '**Most complex functions**', '', '| Function | Location | Complexity | Nesting | Lines |', '|---|---|---:|---:|---:|');
  for (const f of cx.mostComplexFunctions.slice(0, 10)) L.push(`| ${esc(f.name)} | \`${esc(f.path)}:${f.line}\` | ${f.complexity} | ${f.nesting} | ${f.length} |`);
  L.push('');

  L.push('## 7. Dependencies', '', `Vulnerability data: ${deps.vulnerabilityData}. Versions are reported as declared / locked.`, '', '| Ecosystem | Direct | Transitive |', '|---|---:|---:|');
  for (const e of deps.ecosystems) L.push(`| ${e.ecosystem} | ${e.direct} | ${e.transitive} |`);
  L.push('');
  const directDeps = deps.dependencies.filter((d: any) => d.direct);
  if (directDeps.length) {
    L.push('| Package | Declared | Resolved | Type | Manifest |', '|---|---|---|---|---|');
    for (const d of directDeps.slice(0, 60)) L.push(`| ${esc(d.name)} | ${esc(d.spec) || '—'} | ${esc(d.resolved) || '—'} | ${d.dev ? 'dev' : 'prod'} | \`${esc(d.manifest)}\` |`);
    L.push('');
  }
  if (deps.issues.length) {
    L.push('**Dependency issues**', '');
    for (const i of deps.issues.slice(0, 30)) L.push(`- [${SEV_LABEL[i.severity]}] ${esc(i.title)}: ${esc(i.description)} (\`${esc(i.path)}\`)`);
    L.push('');
  }

  L.push('## 8. Technical debt', '', td.method, '');
  td.items.forEach((it, i) => {
    L.push(`### ${i + 1}. ${it.title} — impact ${it.impact}, priority ${it.priority}`, '', it.summary, '', `*Recommendation:* ${it.recommendation}`, '');
    for (const e of it.evidence.slice(0, 6)) L.push(`- \`${esc(e.path)}${e.line ? `:${e.line}` : ''}\` — ${esc(e.detail).slice(0, 200)}`);
    L.push('');
  });
  if (!td.items.length) L.push('No technical-debt indicators were found.', '');

  L.push('## 9. AI review summary', '');
  if (ai?.aiAvailable && ai.files?.length) {
    L.push(`Local AI reviewed ${ai.reviewed} of ${ai.considered} candidate file(s)${ai.folder ? ` in \`${esc(ai.folder)}\`` : ''} on ${ai.createdAt} UTC. AI suggestions can be wrong and were not verified automatically.`, '');
    for (const f of ai.files.slice(0, 15)) L.push(`- \`${esc(f.path)}\` (${f.issues} issue(s)): ${esc(f.summary).slice(0, 300)}`);
  } else L.push('No AI review was run for this report; all findings come from static analysis.');
  L.push('');

  L.push('## 10. Recommended next steps', '');
  const steps: string[] = [];
  if (s.findingsBySeverity.critical) steps.push(`Fix the ${s.findingsBySeverity.critical} critical finding(s) first (secrets must also be rotated).`);
  if (s.findingsBySeverity.high) steps.push(`Review the ${s.findingsBySeverity.high} high-severity finding(s); dismiss false positives so the score reflects real issues.`);
  for (const it of td.items.slice(0, 3)) steps.push(`${it.title}: ${it.recommendation}`);
  if (!s.testFiles) steps.push('Add automated tests before refactoring.');
  (steps.length ? steps : ['Keep the analysis green by re-running it after each change.']).forEach((x, i) => L.push(`${i + 1}. ${x}`));
  L.push('');

  L.push('## 11. Limitations', '');
  for (const l of a.limitations ?? []) L.push(`- ${l}`);
  L.push('- Findings marked "low" confidence are heuristics and need human review.', '- Local AI findings come from a small local model and may be inaccurate.', '');
  L.push('## Appendix — rules', '', '| Rule | Title | Method | Confidence |', '|---|---|---|---|');
  for (const r of RULES) L.push(`| ${r.id} | ${esc(r.title)} | ${r.method} | ${r.confidence} |`);
  L.push('');
  return { markdown: L.join('\n'), title: `Code Quality Report — ${repo.name}`, complete };
}

// ------------------------------------------------------------------ Markdown → print HTML (subset used above)
function inline(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/\*([^*]+)\*/g, '<em>$1</em>')
    .replace(/\\\|/g, '|');
}
export function markdownToHtml(md: string, title: string): string {
  const out: string[] = [];
  const lines = md.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (l.startsWith('|') && lines[i + 1]?.startsWith('|---')) {
      const cells = (row: string) => row.slice(1, -1).split(/(?<!\\)\|/).map((c) => c.trim());
      const head = cells(l);
      const align = cells(lines[i + 1]).map((c) => (c.endsWith(':') ? 'right' : 'left'));
      out.push('<table><thead><tr>' + head.map((h, k) => `<th style="text-align:${align[k]}">${inline(h)}</th>`).join('') + '</tr></thead><tbody>');
      i += 2;
      while (i < lines.length && lines[i].startsWith('|')) {
        out.push('<tr>' + cells(lines[i]).map((c, k) => `<td style="text-align:${align[k]}" class="${/^(Critical|High|Medium|Low|Info)$/.test(c) ? 'sev sev-' + c.toLowerCase() : ''}">${inline(c)}</td>`).join('') + '</tr>');
        i++;
      }
      i--;
      out.push('</tbody></table>');
    } else if (/^#{1,3} /.test(l)) {
      const n = l.indexOf(' ');
      out.push(`<h${n}>${inline(l.slice(n + 1))}</h${n}>`);
    } else if (l.startsWith('> ')) out.push(`<blockquote>${inline(l.slice(2))}</blockquote>`);
    else if (/^- /.test(l)) {
      out.push('<ul>');
      while (i < lines.length && /^- /.test(lines[i])) out.push(`<li>${inline(lines[i++].slice(2))}</li>`);
      i--;
      out.push('</ul>');
    } else if (/^\d+\. /.test(l)) {
      out.push('<ol>');
      while (i < lines.length && /^\d+\. /.test(lines[i])) out.push(`<li>${inline(lines[i++].replace(/^\d+\. /, ''))}</li>`);
      i--;
      out.push('</ol>');
    } else if (l.trim()) out.push(`<p>${inline(l)}</p>`);
  }
  return `<!doctype html><html><head><meta charset="utf-8"><title>${inline(title)}</title><style>
  @page { size: A4; margin: 16mm 14mm; }
  body { font: 10.5pt/1.45 "Segoe UI", Arial, sans-serif; color: #1b1f2a; }
  h1 { font-size: 20pt; margin: 0 0 6pt; color: #3b2fb5; } h2 { font-size: 14pt; margin: 18pt 0 6pt; border-bottom: 1.5pt solid #e3e1f7; padding-bottom: 3pt; page-break-after: avoid; }
  h3 { font-size: 11.5pt; margin: 12pt 0 4pt; page-break-after: avoid; }
  table { width: 100%; border-collapse: collapse; margin: 6pt 0 10pt; font-size: 9pt; page-break-inside: auto; } tr { page-break-inside: avoid; }
  th { background: #f1f0fb; text-align: left; } th, td { border: 0.6pt solid #d9dce5; padding: 3pt 5pt; vertical-align: top; }
  code { font: 8.5pt Consolas, monospace; background: #f4f5f8; padding: 0 2pt; border-radius: 2pt; word-break: break-all; }
  blockquote { margin: 6pt 0; padding: 6pt 9pt; background: #fff7e6; border-left: 3pt solid #f0a020; }
  .sev { font-weight: 600; } .sev-critical { color: #b00020; } .sev-high { color: #d1432b; } .sev-medium { color: #b7791f; } .sev-low { color: #2b6cb0; } .sev-info { color: #5a6270; }
  </style></head><body>${out.join('\n')}</body></html>`;
}

export function findBrowser(): string | null {
  const pf = process.env['ProgramFiles'] ?? 'C:\\Program Files';
  const pf86 = process.env['ProgramFiles(x86)'] ?? 'C:\\Program Files (x86)';
  const local = process.env.LOCALAPPDATA ?? '';
  const candidates = [
    join(pf86, 'Microsoft', 'Edge', 'Application', 'msedge.exe'),
    join(pf, 'Microsoft', 'Edge', 'Application', 'msedge.exe'),
    join(pf, 'Google', 'Chrome', 'Application', 'chrome.exe'),
    join(pf86, 'Google', 'Chrome', 'Application', 'chrome.exe'),
    local && join(local, 'Google', 'Chrome', 'Application', 'chrome.exe'),
    '/usr/bin/microsoft-edge',
    '/usr/bin/google-chrome',
    '/usr/bin/chromium',
  ].filter(Boolean) as string[];
  return candidates.find((c) => existsSync(c)) ?? null;
}

/** Renders the report HTML to PDF with a headless local browser (isolated profile, no network). */
export function renderPdf(html: string): Promise<Buffer> {
  const browser = findBrowser();
  if (!browser) return Promise.reject(Object.assign(new Error('PDF export needs Microsoft Edge or Google Chrome installed. Download the Markdown report instead, or use the browser print dialog.'), { status: 501 }));
  const dir = mkdtempSync(join(tmpdir(), 'codepilot-pdf-'));
  const htmlPath = join(dir, 'report.html');
  const pdfPath = join(dir, 'report.pdf');
  writeFileSync(htmlPath, html);
  const args = [
    '--headless=new', '--disable-gpu', '--no-first-run', '--no-default-browser-check', '--disable-extensions', '--disable-sync', '--disable-background-networking',
    '--disable-component-update', '--no-pdf-header-footer', '--proxy-server=127.0.0.1:9', '--proxy-bypass-list=<-loopback>', `--user-data-dir=${join(dir, 'profile')}`,
    `--print-to-pdf=${pdfPath}`, pathToFileURL(htmlPath).href,
  ];
  return new Promise((resolve, reject) => {
    execFile(browser, args, { timeout: 60_000, windowsHide: true }, (err) => {
      try {
        if (!existsSync(pdfPath)) return reject(Object.assign(new Error(`PDF rendering failed${err ? `: ${err.message.split('\n')[0]}` : ''}`), { status: 500 }));
        resolve(readFileSync(pdfPath));
      } finally {
        setTimeout(() => rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 }), 500);
      }
    });
  });
}
